#!/usr/bin/env python3
"""Generate solid antialiased Roman glyph masks for the Stick S3.

DejaVu Sans Bold: Bitstream Vera license; DejaVu changes are public domain.
See docs/dejavu-font-license.txt. Run from the repository root:
    python3 scripts/generate-display-fonts.py
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FONT_PATH = Path("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf")
OUTPUT = Path(__file__).resolve().parents[1] / "firmware" / "display_fonts.h"
GLYPHS = "+IVXLC"
FONTS = [("kBadgeFont", 31), ("kMediumBadgeFont", 23),
         ("kSmallBadgeFont", 17), ("kTinyBadgeFont", 13),
         ("kCompactBadgeFont", 11)]


def array(name, data):
    rows = [", ".join(f"0x{byte:02x}" for byte in data[i:i + 16])
            for i in range(0, len(data), 16)]
    return f"const uint8_t {name}[] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def main():
    parts = [
        "// Generated by scripts/generate-display-fonts.py. Do not edit by hand.\n",
        "// DejaVu Sans Bold; Copyright (c) 2003 Bitstream, Inc.\n",
        "// DejaVu changes are public domain. See docs/dejavu-font-license.txt.\n",
        '#pragma once\n#include "count_raster.h"\n\n',
    ]
    for name, size in FONTS:
        font = ImageFont.truetype(str(FONT_PATH), size)
        entries = []
        for index, char in enumerate(GLYPHS):
            left, top, right, bottom = (int(value) for value in font.getbbox(char, anchor="ls"))
            width, height = right - left, bottom - top
            image = Image.new("L", (width, height), 0)
            ImageDraw.Draw(image).text((-left, -top), char, font=font,
                                       fill=255, anchor="ls")
            data = image.tobytes()
            # A bold stroke must have opaque interior pixels, not just an edge.
            if 255 not in data:
                raise ValueError(f"Missing solid glyph interior: {name} {char}")
            bitmap = f"{name}Mask{index}"
            parts.append(array(bitmap, data))
            advance = round(font.getlength(char))
            entries.append(f"  {{'{char}', {width}, {height}, {advance}, "
                           f"{left}, {top}, {bitmap}}}")
        parts.append(f"const count_raster::Glyph {name}Glyphs[] = {{\n" +
                     ",\n".join(entries) + "\n};\n")
        cap = -int(font.getbbox("I", anchor="ls")[1])
        parts.append(f"const count_raster::Font {name} = "
                     f"{{{cap}, {len(GLYPHS)}, {name}Glyphs}};\n\n")
    OUTPUT.write_text("".join(parts).rstrip() + "\n")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
